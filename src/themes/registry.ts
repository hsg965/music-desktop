export function getSkin(id: SkinId | string): SkinDefinition {
  return SKINS.find((s) => s.id === id) ?? SKINS[0];
}

export function applySkinToDocument(skin: SkinDefinition) {
  const root = document.documentElement;
  root.dataset.skin = skin.id;
  root.dataset.layout = skin.layout;
  root.dataset.mode = skin.mode;
  for (const [key, value] of Object.entries(skin.tokens)) {
    root.style.setProperty(`--${key}`, value);
  }
  root.style.setProperty("--bg", skin.tokens.bg);
  root.style.setProperty("--sider-bg", skin.tokens["sider-bg"]);
  root.style.setProperty("--bar-bg", skin.tokens["bar-bg"]);

  // 毛玻璃：亮色更透、深色略实，列表「板」可透出主题背景/插画
  const blur =
    skin.tokens["panel-blur"] && skin.tokens["panel-blur"] !== "0px"
      ? skin.tokens["panel-blur"]
      : skin.mode === "light"
        ? "20px"
        : "16px";
  root.style.setProperty("--glass-blur", blur);
  if (skin.mode === "light") {
    root.style.setProperty("--glass-bg", "rgba(255, 255, 255, 0.42)");
    root.style.setProperty("--glass-bg-light", "rgba(255, 255, 255, 0.48)");
    root.style.setProperty("--glass-border", "rgba(255, 255, 255, 0.72)");
  } else {
    root.style.setProperty("--glass-bg", "rgba(255, 255, 255, 0.07)");
    root.style.setProperty("--glass-bg-light", "rgba(255, 255, 255, 0.1)");
    root.style.setProperty("--glass-border", "rgba(255, 255, 255, 0.12)");
  }

  root.style.colorScheme = skin.mode;
}
